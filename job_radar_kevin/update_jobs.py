def is_valid_job(j):
    if j.get("experienceYears", 0) > 4:
        return False
    url = j.get("url", "").lower()
    if "mx.computrabajo.com" in url or j.get("portal", "") == "Computrabajo MX":
        return False
    co = j.get("company", "").lower()
    if any(b in co for b in ["bairesdev", "fullstack", "indii", "lundi"]):
        return False
    combined = " ".join([
        j.get("title", ""),
        j.get("description", ""),
        " ".join(j.get("stack", []))
    ]).lower()
    if any(cloud in combined for cloud in ["aws", "amazon web services", "azure"]):
        return False
    return True


def save_payload(jobs_list):
    filtered_jobs = [j for j in jobs_list if is_valid_job(j)]

    payload = {
        "lastUpdated": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "exchangeRatesNote": "1 EUR ≈ RD$ 65.50 | 1 USD ≈ RD$ 60.50",
        "profile": KEVIN_PROFILE,
        "totalJobs": len(filtered_jobs),
        "jobs": filtered_jobs
    }
    json_path = os.path.join(BASE_DIR, "jobs_data.json")
    js_path = os.path.join(BASE_DIR, "jobs_data.js")

    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)

    with open(js_path, "w", encoding="utf-8") as f:
        f.write("window.JOBS_DATA = ")
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write(";\n")

    print(f"Saved {len(filtered_jobs)} clean jobs (0 BairesDev/FullStack/Indii, 0 AWS/Azure, 0 MX) to {js_path}")


if __name__ == "__main__":
    save_payload(INITIAL_JOBS)
